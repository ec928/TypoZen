/**
 * Regenerate TypoZen_Template_Test.html from the files that actually ship.
 *
 * Every jsdom suite boots by taking the largest inline <script> out of
 * TypoZen_Template_Test.html -- either to eval whole (JSDOM boot) or to pull single
 * functions out of via extractFunction(). That was fine when the app was one monolithic
 * HTML file. After the JS/CSS split, and again after the module split, the test template
 * must be rebuilt from the live sources or suites pin themselves to a frozen snapshot.
 *
 * Running this before the suites keeps the fixture equal to the shipped code. It is
 * invoked by both Build_TypoZen.ps1 and tests/run-tests.ps1; run it by hand with:
 *
 *   node tests/build-test-template.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import {
    appDir,
    engineModulePaths,
    readEngineSource,
    ENGINE_BEGIN,
    ENGINE_END,
} from './engine-source.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const templatePath = path.join(appDir, 'TypoZen_Template.html');
const cssPath = path.join(appDir, 'css', 'typozen.css');
const outPath = path.join(appDir, 'TypoZen_Template_Test.html');

function main() {
    const modulePaths = engineModulePaths();
    for (const p of [templatePath, cssPath, ...modulePaths]) {
        if (!fs.existsSync(p)) {
            console.error('build-test-template: missing ' + p);
            process.exit(1);
        }
    }

    const template = fs.readFileSync(templatePath, 'utf8');
    const css = fs.readFileSync(cssPath, 'utf8');
    const js = readEngineSource();

    const LINK_TAG = '<link rel="stylesheet" href="css/typozen.css">';
    if (template.indexOf(LINK_TAG) === -1) {
        console.error('build-test-template: could not find the stylesheet link in TypoZen_Template.html');
        console.error('  expected: ' + LINK_TAG);
        process.exit(1);
    }
    if (template.indexOf(ENGINE_BEGIN) === -1 || template.indexOf(ENGINE_END) === -1) {
        console.error('build-test-template: TypoZen_Template.html is missing engine markers.');
        console.error('  expected ' + ENGINE_BEGIN + ' … ' + ENGINE_END);
        process.exit(1);
    }

    const banner = '<!-- GENERATED by tests/build-test-template.mjs -- do not edit.\n' +
        '     Inlined copy of TypoZen_Template.html + css/typozen.css + js/modules/*,\n' +
        '     so the jsdom suites exercise the code that actually ships. -->\n';

    const engineBlockRe = new RegExp(
        ENGINE_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
        '[\\s\\S]*?' +
        ENGINE_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    );

    // Function replacements, not string ones.
    //
    // String.replace treats $&, $`, $' and $1 in a *string* replacement as references to
    // the match, so any engine or stylesheet source containing one is spliced into the
    // output wrong. That is not hypothetical: `word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')`
    // is how you escape a word for a regex, it appears in the engine, and it silently
    // substituted the entire matched engine block into the middle of the bundle. The
    // fixture came out corrupt and the only symptom was this script's own sanity check
    // failing with "the largest inline script is not the engine bundle".
    const out = banner + template
        .replace(LINK_TAG, () => '<style id="inlined-typozen-css">\n' + css + '\n</style>')
        .replace(engineBlockRe, () => ENGINE_BEGIN + '\n<script>\n' + js + '\n</script>\n' + ENGINE_END);

    // The suites select the largest inline <script>; make sure that is the app.
    const scripts = [...out.matchAll(/<script>([\s\S]*?)<\/script>/gi)].map(m => m[1]);
    const largest = scripts.sort((a, b) => b.length - a.length)[0] || '';
    if (largest.indexOf('function htmlToMarkdown') === -1) {
        console.error('build-test-template: the largest inline script is not the engine bundle.');
        process.exit(1);
    }
    if (largest.indexOf('function PageChunks') === -1 && largest.indexOf('const PageChunks') === -1 &&
        largest.indexOf('PageChunks =') === -1) {
        // PageChunks is an object const — soft check on DocumentModel instead
        if (largest.indexOf('DocumentModel') === -1) {
            console.error('build-test-template: engine bundle looks incomplete (no DocumentModel).');
            process.exit(1);
        }
    }

    const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
    if (prev === out) {
        console.log('build-test-template: TypoZen_Template_Test.html already current.');
        return;
    }
    fs.writeFileSync(outPath, out, 'utf8');
    console.log('build-test-template: regenerated TypoZen_Template_Test.html (' + out.length +
        ' chars, ' + modulePaths.length + ' modules).');
}

main();
