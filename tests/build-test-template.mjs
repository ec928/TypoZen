/**
 * Regenerate TypoZen_Template_Test.html from the files that actually ship.
 *
 * Every jsdom suite boots by taking the largest inline <script> out of
 * TypoZen_Template_Test.html -- either to eval whole (JSDOM boot) or to pull single
 * functions out of via extractFunction(). That was fine when the app was one monolithic
 * HTML file. After the JS/CSS split on 1 Aug, TypoZen_Template.html started loading
 * css/typozen.css and js/typozen.js by reference, and nothing regenerated the test
 * template -- so the suites silently pinned themselves to a frozen snapshot.
 *
 * By the time this script was written the snapshot was ~28,600 characters behind and was
 * missing htmlToMarkdown, walkTable and set_column_mode entirely: the whole clipboard
 * conversion path and all of the Phase 4 column work were untestable, while the suite
 * still reported green.
 *
 * Running this before the suites keeps the fixture equal to the shipped code. It is
 * invoked by both Build_TypoZen.ps1 and tests/run-tests.ps1; run it by hand with:
 *
 *   node tests/build-test-template.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.join(__dirname, '..');

const templatePath = path.join(appDir, 'TypoZen_Template.html');
const cssPath = path.join(appDir, 'css', 'typozen.css');
const jsPath = path.join(appDir, 'js', 'typozen.js');
const outPath = path.join(appDir, 'TypoZen_Template_Test.html');

const LINK_TAG = '<link rel="stylesheet" href="css/typozen.css">';
const SCRIPT_TAG = '<script src="js/typozen.js"></script>';

function main() {
    for (const p of [templatePath, cssPath, jsPath]) {
        if (!fs.existsSync(p)) {
            console.error('build-test-template: missing ' + p);
            process.exit(1);
        }
    }

    const template = fs.readFileSync(templatePath, 'utf8');
    const css = fs.readFileSync(cssPath, 'utf8');
    const js = fs.readFileSync(jsPath, 'utf8');

    if (template.indexOf(LINK_TAG) === -1) {
        console.error('build-test-template: could not find the stylesheet link in TypoZen_Template.html');
        console.error('  expected: ' + LINK_TAG);
        process.exit(1);
    }
    if (template.indexOf(SCRIPT_TAG) === -1) {
        console.error('build-test-template: could not find the script tag in TypoZen_Template.html');
        console.error('  expected: ' + SCRIPT_TAG);
        process.exit(1);
    }

    const banner = '<!-- GENERATED by tests/build-test-template.mjs -- do not edit.\n' +
        '     Inlined copy of TypoZen_Template.html + css/typozen.css + js/typozen.js,\n' +
        '     so the jsdom suites exercise the code that actually ships. -->\n';

    const out = banner + template
        .replace(LINK_TAG, '<style id="inlined-typozen-css">\n' + css + '\n</style>')
        .replace(SCRIPT_TAG, '<script>\n' + js + '\n</script>');

    // The suites select the largest inline <script>; make sure that is the app.
    const scripts = [...out.matchAll(/<script>([\s\S]*?)<\/script>/gi)].map(m => m[1]);
    const largest = scripts.sort((a, b) => b.length - a.length)[0] || '';
    if (largest.indexOf('function htmlToMarkdown') === -1) {
        console.error('build-test-template: the largest inline script is not js/typozen.js.');
        process.exit(1);
    }

    const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
    if (prev === out) {
        console.log('build-test-template: TypoZen_Template_Test.html already current.');
        return;
    }
    fs.writeFileSync(outPath, out, 'utf8');
    console.log('build-test-template: regenerated TypoZen_Template_Test.html (' + out.length + ' chars).');
}

main();
